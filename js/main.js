
/*
|--------------------------------------------------------------------------
| أولًا: استيراد الوحدات المسؤولة عن واجهة التطبيق
|--------------------------------------------------------------------------
*/

// نستورد bindActions من ملف actions.js.
// من المتوقع أن تربط هذه الدالة إجراءات المستخدم بالأزرار
// والعناصر التي تستخدم سمات مثل data-action.
//
// مثال: الضغط على زر إضافة عملية أو إغلاق نافذة.
// التفاصيل الدقيقة تعتمد على محتوى actions.js.
import { bindActions } from './ui/actions.js';

// نستورد sheet، وهو كائن مسؤول غالبًا عن إدارة اللوحة
// المنبثقة التي تحتوي على نموذج إضافة أو تعديل عملية.
//
// لاحقًا سنستدعي sheet.bind() لربط أحداث اللوحة.
import { sheet } from './ui/sheet.js';

// نستورد ثلاث دوال من نظام التنقل بين الصفحات:
//
// register: تسجيل صفحة وربط اسمها بوحدة عرضها.
// startRouter: تشغيل نظام التنقل.
// refresh: إعادة تحديث الصفحة الحالية أو عرضها من جديد.
//
// سنعرف سلوك كل دالة بالتحديد عند مراجعة router.js.
import {
  register,
  startRouter,
  refresh
} from './ui/router.js';

// نستورد دوال إدارة واجهة تسجيل الدخول.
//
// bindLogin: ربط أحداث نموذج تسجيل الدخول وأزراره.
// showLogin: إظهار شاشة تسجيل الدخول، مع تمرير دالة
// يمكن تشغيلها بعد نجاح تسجيل الدخول، وفق تنفيذ الوحدة.
import {
  bindLogin,
  showLogin
} from './ui/login.js';

// نستورد دالة تهيئة ميزة تثبيت التطبيق.
// من المتوقع أن تربط زر التثبيت بحدث beforeinstallprompt
// الذي حفظناه سابقًا في index.html.
import { initInstall } from './ui/install.js';

// نستورد كائن المصادقة auth.
//
// يحتوي، وفق طريقة استخدامه هنا، على دوال للتحقق من
// حالة تسجيل الدخول ومراقبة حالة المستخدم.
import { auth } from './services/auth.js';


/*
|--------------------------------------------------------------------------
| ثانيًا: استيراد وحدات تنفذ عملها عند تحميلها
|--------------------------------------------------------------------------
*/

// هذه الاستيرادات لا تستورد اسم دالة أو كائن بعينه.
//
// عندما تُحمّل JavaScript وحدة ES Module لأول مرة،
// تُنفّذ تعليماتها الموجودة في المستوى الأعلى مرة واحدة
// ضمن دورة التحميل العادية لتلك الوحدة.
//
// لذلك قد تكون هذه الملفات مسؤولة عن تسجيل أحداث
// أو إعداد نماذج أو ربط واجهات محددة.
//
// لا يمكن الجزم بما تفعله بالضبط دون مراجعة محتواها.
import './ui/entry.js';
import './ui/productSheet.js';
import './ui/supplierSheet.js';


/*
|--------------------------------------------------------------------------
| ثالثًا: استيراد وحدات الصفحات
|--------------------------------------------------------------------------
*/

// كل وحدة من هذه الوحدات تمثل صفحة من صفحات التطبيق.
//
// dashboard: لوحة التحكم الرئيسية.
// home: قسم البيت.
// invest: قسم الاستثمار.
// reports: قسم التقارير.
// settings: قسم الإعدادات.
//
// استخدام import باسم افتراضي default import يعني أن
// كل ملف يصدّر قيمة افتراضية باستخدام export default.
import dashboard from './ui/pages/dashboard.js';
import home from './ui/pages/home.js';
import invest from './ui/pages/invest.js';
import reports from './ui/pages/reports.js';
import settings from './ui/pages/settings.js';


/*
|--------------------------------------------------------------------------
| رابعًا: ربط إجراءات الواجهة
|--------------------------------------------------------------------------
*/

// نطلب من وحدة actions.js تهيئة التعامل مع الإجراءات.
//
// قد تستخدم هذه الوحدة مستمع أحداث عامًّا بدل ربط
// مستمع منفصل بكل زر، لكن يجب مراجعة الملف للتأكد.
//
// الاستدعاء هنا يجهّز سلوك الأزرار قبل تشغيل الصفحات.
bindActions();

// نربط أحداث اللوحة المنبثقة.
// هذا يسمح لوحدة sheet بالتعامل مع الفتح والإغلاق
// أو التفاعل مع النموذج بحسب تنفيذها.
sheet.bind();

// نربط أحداث شاشة تسجيل الدخول، مثل إرسال النموذج
// والتعامل مع إظهار كلمة السر.
bindLogin();

// نهيئ وظيفة تثبيت التطبيق.
// قد تربط هذه الدالة زر التثبيت بالحدث المحفوظ
// في window.__bip، حسب كود ui/install.js.
initInstall();


/*
|--------------------------------------------------------------------------
| خامسًا: تسجيل صفحات التطبيق في نظام التنقل
|--------------------------------------------------------------------------
*/

// نربط اسم كل صفحة بوحدة JavaScript المسؤولة عن عرضها.
//
// عند تسجيل 'dashboard' مثلًا، يستطيع نظام التنقل
// التعرف على الصفحة المرتبطة بهذا الاسم.
//
// عند انتقال المستخدم إلى #/dashboard، يفترض أن يستخدم
// router الوحدة المسجلة لعرض محتوى لوحة التحكم.
//
// الأسماء هنا يجب أن تتوافق مع أسماء المسارات
// التي يتعامل معها router.js.
register('dashboard', dashboard);
register('home', home);
register('invest', invest);
register('reports', reports);
register('settings', settings);


/*
|--------------------------------------------------------------------------
| سادسًا: تجهيز حالة تشغيل التطبيق
|--------------------------------------------------------------------------
*/

// متغير يحدد هل بدأ نظام التنقل بالفعل أم لا.
//
// false تعني أن startRouter لم يُستدعَ بعد من خلال boot.
// true تعني أن boot سبق أن بدأ نظام التنقل.
let started = false;


// دالة boot مسؤولة عن بدء واجهة التطبيق أو تحديثها.
function boot() {

  // نحذف الصنف locked من body.
  //
  // في index.html بدأنا بـ:
  // <body class="locked">
  //
  // إزالة الصنف تسمح لقواعد CSS المرتبطة به بالتوقف عن العمل.
  // قد يؤدي ذلك إلى إظهار الواجهة أو إعادة تفعيل التمرير،
  // وفق القواعد الموجودة في css/style.css.
  document.body.classList.remove('locked');

  // إذا كان نظام التنقل قد بدأ سابقًا...
  if (started) {

    // نحدّث العرض الحالي بدل تشغيل الراوتر مرة أخرى.
    // هذا مفيد عند العودة إلى التطبيق بعد تسجيل الدخول
    // أو بعد إظهار شاشة الدخول مجددًا.
    refresh();

  } else {

    // نسجل أن عملية بدء الراوتر ستبدأ الآن.
    started = true;

    // نبدأ نظام التنقل بين صفحات التطبيق لأول مرة.
    // من المتوقع أن يقرأ المسار الحالي ويعرض الصفحة المناسبة.
    startRouter();
  }
}


/*
|--------------------------------------------------------------------------
| سابعًا: التحقق من تسجيل الدخول عند بدء التطبيق
|--------------------------------------------------------------------------
*/

// نسأل auth إذا كان المستخدم مسجل الدخول حاليًا.
//
// إذا أعادت isLoggedIn() القيمة true:
if (auth.isLoggedIn()) {

  // نبدأ التطبيق مباشرة دون عرض شاشة الدخول.
  boot();

} else {

  // إذا لم يكن المستخدم مسجل الدخول، نعرض شاشة الدخول.
  //
  // نمرر boot كدالة callback حتى تتمكن وحدة تسجيل الدخول
  // من استدعائها بعد نجاح التحقق، حسب تنفيذ showLogin.
  showLogin(boot);
}


/*
|--------------------------------------------------------------------------
| ثامنًا: التعامل مع مغادرة المستخدم أو انتهاء الجلسة
|--------------------------------------------------------------------------
*/

// نسجل callback لدى auth لمراقبة الحالة التي تسميها
// الوحدة watchAway.
//
// لا نعرف من هذا الملف وحده هل المقصود انتهاء الجلسة،
 // أو مغادرة التطبيق، أو حدث آخر؛ نحتاج مراجعة auth.js.
auth.watchAway(() => {

  // إذا كانت هناك لوحة منبثقة مفتوحة، نغلقها.
  // هذا يمنع بقاء نموذج ظاهر أثناء الانتقال إلى شاشة الدخول.
  sheet.close();

  // نعرض شاشة تسجيل الدخول مجددًا،
  // ونمرر boot لتشغيل التطبيق بعد إتمام الدخول بنجاح.
  showLogin(boot);
});


/*
|--------------------------------------------------------------------------
| تاسعًا: تسجيل Service Worker
|--------------------------------------------------------------------------
*/

// نتحقق أولًا من أن المتصفح يدعم Service Worker.
//
// navigator.serviceWorker هي الواجهة التي تتيح للصفحة
// تسجيل Service Worker والتواصل مع آلية عمله.
if ('serviceWorker' in navigator) {

  // نسجل الملف sw.js بوصفه Service Worker للتطبيق.
  //
  // بعد التسجيل، يستطيع المتصفح تثبيته وتفعيله وفق قواعده،
  // ثم تشغيل أحداث install وactivate وfetch الموجودة داخله.
  //
  // المسار النسبي 'sw.js' يعتمد على مكان نشر الصفحة
  // والمسار الأساسي للمستند.
  navigator.serviceWorker.register('sw.js');
}
