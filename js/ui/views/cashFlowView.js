
/**
 * balances: حساب الأرصدة الحالية للأقسام والحسابات.
 * cashFlow: حساب حركة الأموال الداخلة والخارجة من الاستثمار.
 */
import {
  balances,
  cashFlow
} from '../../domain/ledger.js';

/**
 * حساب قيمة المخزون الحالي بسعر التكلفة.
 */
import { inventoryValue } from '../../domain/inventory.js';

/**
 * حساب إجمالي الديون المستحقة على المشروع.
 */
import { debtTotal } from '../../domain/debts.js';

/**
 * EPS: هامش صغير لتجنب التعامل مع الفروق المالية
 * البسيطة جدًا باعتبارها قيمة مؤثرة.
 */
import { EPS } from '../../core/constants.js';

/**
 * تنسيق المبالغ المالية للعرض.
 */
import { fmt } from '../../core/format.js';

/**
 * إنشاء صف إحصائي لعرض اسم البند وقيمته.
 */
import { stat } from '../components.js';

/**
 * عرض تفصيل يشرح للمستخدم:
 * كيف حُسب الرصيد النقدي للاستثمار؟
 * وكيف حُسبت قيمة الاستثمار الكلية؟
 */
export function cashFlowView(state) {

  // حساب حركة الأموال الداخلة والخارجة من الاستثمار.
  const f = cashFlow(state);

  // الرصيد النقدي الحالي لقسم الاستثمار.
  const cash = balances(state).invest;

  // القيمة الحالية للمخزون محسوبة بسعر التكلفة.
  const inv = inventoryValue(state);

  // إجمالي الديون المستحقة على المشروع.
  const debt = debtTotal(state);

  return `
    <!-- قسم قابل للفتح والإغلاق لشرح الحسابات -->
    <details class="det">

      <summary>كيف انحسب رصيد الاستثمار؟</summary>

      <!-- تفاصيل طريقة حساب الرصيد النقدي -->
      <div class="list">

        <!-- رأس المال والتحويلات الداخلة إلى الاستثمار -->
        ${stat(
          'رأس المال والتحويلات الداخلة',
          fmt(f.capital)
        )}

        <!--
          إضافة إجمالي المبيعات.
          وفق هذا التصميم، المبيعات تشمل تكلفة البضاعة
          والربح، وليست الربح وحده.
        -->
        ${stat(
          '＋ المبيعات (كاملة: تكلفة + ربح)',
          fmt(f.sales),
          'pos'
        )}

        <!-- خصم المشتريات التي دُفع ثمنها فعليًا -->
        ${stat(
          '－ مشتريات مدفوعة',
          fmt(f.paidPurchases),
          'neg'
        )}

        <!-- خصم المبالغ المدفوعة لسداد الديون، إذا كانت موجودة -->
        ${
          f.debtPayments
            ? stat(
                '－ سداد ديون',
                fmt(f.debtPayments),
                'neg'
              )
            : ''
        }

        <!-- خصم المصروفات المدفوعة من الاستثمار -->
        ${stat(
          '－ مصاريف',
          fmt(f.expenses),
          'neg'
        )}

        <!-- عرض الرصيد النقدي الفعلي الحالي -->
        ${stat(
          '= الرصيد النقدي',
          fmt(cash),
          '',
          true
        )}

      </div>

      <!-- مسافة بين حساب النقد وحساب القيمة الكلية -->
      <div class="gap"></div>

      <!-- حساب القيمة الكلية للاستثمار -->
      <div class="list">

        <!-- الأموال النقدية الموجودة حاليًا -->
        ${stat(
          'الرصيد النقدي',
          fmt(cash)
        )}

        <!--
          إضافة قيمة البضاعة الموجودة في المخزون،
          محسوبة بسعر التكلفة وليس سعر البيع.
        -->
        ${stat(
          '＋ قيمة المخزون (بسعر التكلفة)',
          fmt(inv)
        )}

        <!--
          خصم الديون المستحقة على المشروع فقط إذا
          تجاوزت قيمة الدين هامش EPS.
        -->
        ${
          debt > EPS
            ? stat(
                '－ ديون عليك',
                fmt(debt),
                'neg'
              )
            : ''
        }

        <!-- صافي قيمة الاستثمار بعد إضافة المخزون وخصم الديون -->
        ${stat(
          '= قيمة الاستثمار الكلية',
          fmt(cash + inv - debt),
          '',
          true
        )}

      </div>

      <!-- شرح مبسط للمستخدم -->
      <div class="nt">
        الرصيد النقدي هو المال الموجود فعلاً بالاستثمار.
        المبيعات بتدخله كاملة، والمخزون ما هو داخل فيه
        وإنما بيتحسب بالقيمة الكلية.
      </div>

    </details>
  `;
}
