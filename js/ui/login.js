
/**
 * استيراد دالة اختيار عناصر HTML باستخدام محدد CSS.
 */
import { $ } from './dom.js';

// خدمة المصادقة المسؤولة عن التحقق من بيانات المستخدم وتسجيل دخوله.
import { auth } from '../services/auth.js';

// خدمة التثبيت، وتُستخدم هنا لمعرفة ما إذا كان الجهاز جوالاً.
import { install } from '../services/install.js';


// دالة تُنفذ بعد نجاح تسجيل الدخول.
// افتراضياً لا تفعل شيئاً إلى أن يتم تمرير دالة إليها.
let afterLogin = () => {
};


/**
 * ربط أحداث نموذج تسجيل الدخول بالأزرار والحقول.
 */
export function bindLogin() {

  // عند الضغط على أيقونة العين، نبدّل طريقة عرض كلمة السر.
  $('#leye').onclick = () => {

    // جلب حقل كلمة السر.
    const input = $('#lp');

    // إذا كان الحقل من نوع password، سنحوّله إلى نص ظاهر.
    const show = input.type === 'password';

    // إظهار كلمة السر أو إخفاؤها حسب حالتها الحالية.
    input.type = show ? 'text' : 'password';

    // تغيير الأيقونة لتوضيح الحالة الحالية للمستخدم.
    $('#leye').textContent = show ? '🙈' : '👁';
  };


  // عند إرسال نموذج تسجيل الدخول.
  $('#lform').onsubmit = async e => {

    // منع المتصفح من إعادة تحميل الصفحة عند إرسال النموذج.
    e.preventDefault();

    // التحقق من اسم المستخدم وكلمة السر عبر خدمة المصادقة.
    // await ينتظر نتيجة التحقق قبل الانتقال للخطوة التالية.
    if (await auth.check($('#lu').value, $('#lp').value)) {

      // تسجيل الدخول بعد نجاح التحقق.
      auth.login();

      // مسح كلمة السر من الحقل بعد نجاح تسجيل الدخول.
      $('#lp').value = '';

      // مسح رسالة الخطأ السابقة إن وُجدت.
      $('#lerr').textContent = '';

      // تنفيذ الإجراء الذي تم تمريره عند عرض شاشة الدخول.
      // قد يكون مثلاً فتح التطبيق أو الانتقال إلى الصفحة الرئيسية.
      afterLogin();

    } else {

      // إذا كانت البيانات غير صحيحة، نعرض رسالة واضحة للمستخدم.
      $('#lerr').textContent =
        'اسم المستخدم أو كلمة السر غير صحيحة';

      // مسح كلمة السر حتى يعيد المستخدم إدخالها.
      $('#lp').value = '';

      // إعادة التركيز إلى حقل كلمة السر لتسهيل المحاولة التالية.
      $('#lp').focus();
    }
  };
}


/**
 * عرض شاشة تسجيل الدخول وتجهيزها.
 *
 * onSuccess: دالة تُنفذ بعد نجاح تسجيل الدخول.
 */
export function showLogin(onSuccess) {

  // حفظ الدالة التي يجب تنفيذها بعد نجاح تسجيل الدخول.
  afterLogin = onSuccess;

  // إضافة الكلاس locked إلى الصفحة.
  // يُفترض أن CSS يستخدمه لمنع الوصول إلى واجهة التطبيق قبل الدخول.
  document.body.classList.add('locked');

  // تنظيف حقل كلمة السر ورسالة الخطأ عند عرض الشاشة.
  $('#lp').value = '';
  $('#lerr').textContent = '';

  // إذا كانت بيانات الدخول الافتراضية ما زالت مستخدمة،
  // نعرض للمستخدم تعليمات أول دخول.
  // وإلا نترك مكان التعليمات فارغاً.
  $('#lhint').textContent = auth.isDefault()
    ? 'أول دخول: اسم المستخدم 123 · كلمة السر 123'
    : '';

  // على الأجهزة غير المحمولة، نضع المؤشر تلقائياً
  // في حقل اسم المستخدم بعد 150 مللي ثانية.
  // التأخير القصير يسمح بظهور واجهة الدخول أولاً.
  if (!install.isMobile) {
    setTimeout(() => $('#lu').focus(), 150);
  }
}
