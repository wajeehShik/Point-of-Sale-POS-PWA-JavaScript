
/*
 * استيراد دالة today من ملف format.js.
 * يُفترض أن الدالة تُرجع تاريخ اليوم بصيغة:
 * YYYY-MM-DD
 *
 * مثال: 2026-10-12
 */
import { today } from './format.js';

/*
 * أسماء أيام الأسبوع بالعربية.
 *
 * JavaScript يعيد رقم اليوم من Date.getDay():
 * الأحد = 0، الاثنين = 1، ... السبت = 6.
 *
 * لذلك ترتيب العناصر هنا مهم جدًا.
 */
export const DAYS = [
  'الأحد',
  'الاثنين',
  'الثلاثاء',
  'الأربعاء',
  'الخميس',
  'الجمعة',
  'السبت',
];

/*
 * أسماء الأشهر بالعربية، من يناير إلى ديسمبر.
 *
 * الأشهر في JavaScript تبدأ من الرقم 0:
 * يناير = 0، فبراير = 1، ... ديسمبر = 11.
 */
export const MONTHS = [
  'كانون الثاني',
  'شباط',
  'آذار',
  'نيسان',
  'أيار',
  'حزيران',
  'تموز',
  'آب',
  'أيلول',
  'تشرين الأول',
  'تشرين الثاني',
  'كانون الأول',
];

/*
 * تحويل الأرقام إلى نص من خانتين.
 *
 * pad(3)  => "03"
 * pad(12) => "12"
 *
 * نستخدمها للحفاظ على تنسيق التاريخ.
 */
const pad = n => String(n).padStart(2, '0');

/*
 * تكوين تاريخ بصيغة YYYY-MM-DD.
 *
 * تستقبل:
 * y = السنة
 * m = الشهر، ويبدأ من صفر وفق JavaScript
 * d = رقم اليوم
 *
 * ميزة Date هنا أنها تصحح القيم الخارجة عن المدى تلقائيًا.
 * مثلًا: الشهر -1 ينتقل إلى السنة السابقة.
 *
 * ملاحظة: الشهر هنا يبدأ من صفر، وليس من 1.
 */
export const ymd = (y, m, d) => {
  const dt = new Date(y, m, d);

  return `${dt.getFullYear()}-${pad(dt.getMonth() + 1)}-${pad(dt.getDate())}`;
};

/*
 * تحويل التاريخ من:
 * "2026-10-12"
 * إلى:
 * "12/10"
 *
 * لا تعرض السنة؛ مناسبة للعناوين المختصرة.
 */
export const shortDate = s => {
  const [, m, d] = s.split('-');
  return `${+d}/${+m}`;
};

/*
 * استقبال الشهر بصيغة YYYY-MM،
 * ثم إرجاع اسمه بالعربية مع السنة.
 *
 * مثال:
 * monthName("2026-10") => "تشرين الأول 2026"
 */
export const monthName = m =>
  `${MONTHS[+m.slice(5, 7) - 1]} ${m.slice(0, 4)}`;

/*
 * معرفة اسم يوم الأسبوع لتاريخ معين.
 *
 * مثال:
 * weekday("2026-10-12") => "الاثنين"
 *
 * نقسم النص إلى سنة وشهر ويوم،
 * ثم ننشئ Date، مع طرح 1 من الشهر
 * لأن أشهر JavaScript تبدأ من صفر.
 */
export const weekday = ds => {
  const [y, m, d] = ds.split('-').map(Number);

  return DAYS[new Date(y, m - 1, d).getDay()];
};

/*
 * إنشاء وصف عربي للتاريخ:
 *
 * إذا كان التاريخ اليوم:
 * "اليوم · الاثنين 12/10"
 *
 * إذا كان أمس:
 * "أمس · الأحد 11/10"
 *
 * وإذا كان تاريخًا آخر:
 * "الأربعاء 7/10"
 *
 * تُضاف السنة عندما لا تكون سنة التاريخ
 * هي السنة الحالية.
 */
export function dayLabel(ds) {
  const [y, m, d] = ds.split('-').map(Number);

  // إظهار السنة فقط عندما تكون مختلفة عن السنة الحالية.
  const year = y !== new Date().getFullYear() ? '/' + y : '';

  // بناء الوصف الأساسي: اسم اليوم + اليوم والشهر.
  const base = `${weekday(ds)} ${d}/${m}${year}`;

  // هل التاريخ هو اليوم؟
  if (ds === today()) {
    return 'اليوم · ' + base;
  }

  // حساب تاريخ أمس.
  const yesterday = new Date();
  yesterday.setDate(yesterday.getDate() - 1);

  // هل التاريخ هو أمس؟
  return ds === yesterday.toLocaleDateString('sv')
    ? 'أمس · ' + base
    : base;
}
