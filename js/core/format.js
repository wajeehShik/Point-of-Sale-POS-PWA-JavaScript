
/*
 * تقريب الرقم إلى منزلتين عشريتين.
 *
 * أمثلة:
 * r2(12.345) => 12.35
 * r2(12.344) => 12.34
 * r2(15)     => 15
 *
 * يفيد في عرض المبالغ المالية بدقة منزلتين.
 */
export const r2 = n =>
  Math.round(n * 100) / 100;

/*
 * تنسيق المبلغ المالي:
 * 1. تقريب الرقم إلى منزلتين عشريتين.
 * 2. إضافة فواصل الآلاف باستخدام en-US.
 * 3. إضافة رمز الشيكل.
 *
 * أمثلة:
 * fmt(1500)    => "1,500 ₪"
 * fmt(1250.5)  => "1,250.5 ₪"
 * fmt(25.678)  => "25.68 ₪"
 */
export const fmt = n =>
  r2(n).toLocaleString('en-US') + ' ₪';

/*
 * إرجاع تاريخ اليوم بصيغة YYYY-MM-DD.
 *
 * مثال:
 * "2026-10-12"
 *
 * التنسيق sv يُستخدم للحصول على صيغة تاريخ
 * تشبه السنة-الشهر-اليوم، وفق بيئة التشغيل.
 */
export const today = () =>
  new Date().toLocaleDateString('sv');

/*
 * حساب النسبة المئوية:
 *
 * a = الجزء
 * b = الإجمالي
 *
 * إذا كان الإجمالي أكبر من صفر:
 * تُحسب النسبة وتُقرّب إلى عدد صحيح.
 *
 * أمثلة:
 * pct(25, 100) => "25%"
 * pct(1, 3)    => "33%"
 *
 * إذا كان الإجمالي صفرًا أو سالبًا:
 * تُرجع الشرطة الطويلة بدل القسمة.
 */
export const pct = (a, b) =>
  (b > 0
    ? Math.round((a / b) * 100) + '%'
    : '—');
