// استيراد مخزن البيانات الذي يدير حالة التطبيق وحفظ التعديلات
import { store } from '../data/store.js';

// استيراد دالة البحث عن منتج باستخدام المعرّف الخاص به
import { findProduct } from '../domain/lookup.js';

// استيراد دوال حساب المخزون والتحقق من عدم وجود كميات سالبة
import { stock, hasNegativeStock } from '../domain/inventory.js';

// إنشاء نتيجة موحدة لإرجاع رسالة الخطأ عند فشل العملية
const fail = error => ({ error });

/**
 * تعديل بيانات منتج موجود.
 *
 * id: معرّف المنتج.
 * f: البيانات الجديدة، مثل الاسم والسعر والتكلفة والكمية.
 */
export function saveProduct(id, f) {
  // تنفيذ التعديل داخل معاملة في مخزن البيانات
  return store.transact(s => {

    // البحث عن المنتج في بيانات التطبيق
    const p = findProduct(s, id);

    // إذا لم يتم العثور عليه، نوقف التعديل ونرجع رسالة خطأ
    if (!p) return fail('المنتج غير موجود');

    // إزالة المسافات الزائدة من بداية اسم المنتج ونهايته
    const name = (f.name || '').trim();

    // التأكد من أن اسم المنتج ليس فارغاً
    if (!name) return fail('اكتب اسم المنتج');

    // تحويل الكمية المدخلة إلى رقم
    const target = +f.stock;

    // التأكد من أن الكمية رقم صالح وليست سالبة
    if (!(target >= 0)) return fail('الكمية غير صحيحة');

    // حساب كمية المنتج الحالية اعتماداً على سجل العمليات
    const current = stock(s, id);

    // تحديث بيانات المنتج الأساسية
    Object.assign(p, {
      name,                // الاسم الجديد
      cost: +f.cost || 0,  // تكلفة الوحدة، أو صفر إذا كانت القيمة فارغة أو غير صالحة
      price: +f.price || 0,// سعر البيع، أو صفر إذا كانت القيمة فارغة أو غير صالحة
      min: +f.min || 0     // الحد الأدنى للمخزون الذي يظهر عنده تنبيه
    });

    // تعديل رصيد البداية بحيث تصبح الكمية النهائية مساوية للكمية التي أدخلها المستخدم.
    // الفرق بين الكمية المطلوبة والكمية الحالية يُضاف إلى qty0.
    // هذا يشبه إجراء جرد للمخزون دون إنشاء عملية بيع أو شراء جديدة.
    // الضرب والقسمة على مليون يساعدان في تقليل مشاكل الكسور العشرية.
    p.qty0 = Math.round(
      ((+p.qty0 || 0) + target - current) * 1e6
    ) / 1e6;

    // التأكد من أن التعديل لم يجعل مخزون أي منتج سالباً
    if (hasNegativeStock(s)) {
      return fail('الكمية بتخلي المخزون سالب');
    }

    // إذا لم نرجع خطأ، تنتهي الدالة ويُفترض أن المعاملة تحفظ التعديل
  });
}

/**
 * حذف منتج من التطبيق.
 *
 * لا يسمح بالحذف إذا كان المنتج مرتبطاً بعمليات مسجلة.
 */
export function deleteProduct(id) {
  // تنفيذ الحذف داخل معاملة في مخزن البيانات
  return store.transact(s => {

    // التحقق مما إذا كان هناك أي سجل عملية مرتبط بهذا المنتج
    if (s.tx.some(t => t.productId === id)) {
      return fail('المنتج عليه عمليات، احذفها أولاً');
    }

    // حذف المنتج من قائمة المنتجات باستخدام المصفاة
    s.products = s.products.filter(p => p.id !== id);

    // إذا لم يكن المنتج مرتبطاً بعمليات، يتم حذفه
  });
}